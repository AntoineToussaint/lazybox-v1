package runner

import (
	"os"
	"path/filepath"
	"strings"
)

// A login shell rebuilds PATH from the person's profile: macOS's path_helper
// and tools such as Homebrew, mise or cargo put their directories first. When
// one of them holds another `lazybox` (V1 installs one), `cmd | lazybox log`
// in a workspace terminal would run that one instead of this Runner's CLI.
// For zsh, the default macOS shell, the Runner therefore loads the person's
// own startup files unchanged and puts its CLI first on PATH once they have
// all run, before the first prompt. This is the standard way terminals add
// shell integration (ZDOTDIR pointing at a small .zshenv that restores it).
// Other shells get the CLI first on PATH in their initial environment, which
// a profile may reorder; `command -v lazybox` shows which one runs.

// zshIntegration is the .zshenv a workspace terminal's zsh reads first. It
// hands every later startup file back to the person's own ZDOTDIR.
const zshIntegration = `# Lazybox workspace terminal. Generated by the Lazybox Runner; edits are replaced.
# Load your own zsh startup files, then put Lazybox's CLI first on PATH once
# they have all run, so ` + "`lazybox log`" + ` reaches this workspace.
if [[ -n "${LAZYBOX_V2_USER_ZDOTDIR+set}" ]]; then
  ZDOTDIR="$LAZYBOX_V2_USER_ZDOTDIR"
else
  unset ZDOTDIR
fi
unset LAZYBOX_V2_USER_ZDOTDIR
if [[ -f "${ZDOTDIR:-$HOME}/.zshenv" ]]; then
  source "${ZDOTDIR:-$HOME}/.zshenv"
fi
if [[ -n "$LAZYBOX_V2_CLI_DIR" ]]; then
  _lazybox_cli_first() {
    path=("$LAZYBOX_V2_CLI_DIR" ${path:#$LAZYBOX_V2_CLI_DIR})
    precmd_functions=(${precmd_functions:#_lazybox_cli_first})
  }
  typeset -ga precmd_functions
  precmd_functions+=(_lazybox_cli_first)
fi
`

func (b *Bench) zshIntegrationDir() string {
	return filepath.Join(b.Config.State, "terminal-shell", "zsh")
}

// shellIntegration adds what keeps this Runner's CLI first on PATH in the
// shell it is given. Without a CLI, or for a shell other than zsh, env is
// returned unchanged. A failure to write the integration is not fatal: the
// shell still starts, with the CLI first in its initial PATH.
func (b *Bench) shellIntegration(shell string, env []string) []string {
	if b.Config.CLIDir == "" || filepath.Base(shell) != "zsh" {
		return env
	}
	dir := b.zshIntegrationDir()
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return env
	}
	if err := writePrivate(filepath.Join(dir, ".zshenv"), []byte(zshIntegration)); err != nil {
		return env
	}
	out := make([]string, 0, len(env)+3)
	for _, entry := range env {
		if value, ok := strings.CutPrefix(entry, "ZDOTDIR="); ok {
			out = append(out, "LAZYBOX_V2_USER_ZDOTDIR="+value)
			continue
		}
		out = append(out, entry)
	}
	return append(out, "ZDOTDIR="+dir, "LAZYBOX_V2_CLI_DIR="+b.Config.CLIDir)
}

// writePrivate replaces a file atomically, readable by the user alone.
func writePrivate(path string, data []byte) error {
	f, err := os.CreateTemp(filepath.Dir(path), ".write-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err = f.Write(data); err == nil {
		err = f.Sync()
	}
	if closeErr := f.Close(); err == nil {
		err = closeErr
	}
	if err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}
